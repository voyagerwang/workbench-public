/** 资料类事实问题：答案可能只存在于知识库正文里，不检索就只能靠编。 */
export function needsKnowledgeLookup(text: string): boolean {
  return /知识库|云文档|飞书文档|钉钉文档|资料[里中]|归档|存档|(?:文档|手册|规范|制度|纪要|方案|wiki)[里中]?(?:怎么|如何|是|写的|说的|规定|描述)|怎么(?:写|说)的|怎么规定|适用对象|适用范围|之前(?:定|写|说)的|有没有(?:文档|资料|写过|记录)/i.test(text);
}

/** 知识库工具组的触发正则：命中就把 workbench_search_knowledge_base 挂载给模型。 */
export const KNOWLEDGE_TRIGGER =
  /知识库|云文档|飞书文档|钉钉文档|资料|归档|存档|文档|手册|规范|制度|纪要|wiki|适用对象|适用范围|怎么(?:写|说)的|怎么规定|之前(?:定|写|说)的/i;

